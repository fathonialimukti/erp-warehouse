/**
 * The only icon entry point in the app.
 *
 * Every glyph is in-house: 24x24, stroke 1.75, currentColor, round caps and
 * joins (see `docs/design/design.md`). No third-party icon set, no runtime
 * icon fetch, no duplicate visual language.
 *
 *   <AppIcon name="trash" />              // 16px
 *   <AppIcon name="trash" size="md" />    // 20px
 *   <AppIcon name="trash" size={28} />     // raw pixels
 *
 * Adding an icon: draw `assets/icons/icon-<name>.svg`, add it to GLYPHS.
 */

