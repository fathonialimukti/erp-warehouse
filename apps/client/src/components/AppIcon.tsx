export type IconName = keyof typeof GLYPHS;

/** Narrow an unknown value (e.g. a DB column) to a renderable icon name. */
export const isIconName = (value: unknown): value is IconName =>
  typeof value === "string" && value in GLYPHS;

interface AppIconProps extends Omit<SVGProps<SVGSVGElement>, "name"> {
  name: IconName;
  size?: IconSize | number;
}

export function AppIcon({ name, size = "sm", ...props }: AppIconProps) {
  const Glyph = GLYPHS[name];
  const px = typeof size === "number" ? size : SIZE_PX[size];
  return <Glyph width={px} height={px} {...props} />;
}
